import bcrypt from "bcrypt";
import { eq } from "drizzle-orm";

import { db } from "../../db/index";
import { users } from "../../db/schema";
import {
  registrationCache,
  verificationMutex,
} from "../../cache/registrationCache";
import { generateOTP, compareOTP } from "../../utils/otp";
import { addJob } from "../../workers/index";
import { throwError, handleDbError } from "../../utils/serviceError";

import type {
  RegistrationInitiateInput,
  RegistrationVerifyInput,
} from "../../validators/auth.validator";

/**
 * Stage a new registration in the LRU cache and enqueue an OTP email.
 *
 * 1. Rejects duplicate emails already in PostgreSQL.
 * 2. Hashes the password immediately (so the verify step is fast).
 * 3. Stores the full payload + OTP + attempt counter in the cache.
 * 4. Pushes a `send-otp` job to graphile-worker for async delivery.
 *
 * The OTP is NEVER returned or exposed to the client.
 */
async function initiateRegistration(
  payload: RegistrationInitiateInput,
): Promise<{ message: string }> {
  const normalizedEmail = payload.email.trim().toLowerCase();

  // ── Duplicate check against PostgreSQL ──
  const [existing] = await db
    .select({ email: users.email })
    .from(users)
    .where(eq(users.email, normalizedEmail))
    .limit(1);

  if (existing) {
    throwError("Email is already registered", 400);
  }

  // ── Hash password upfront (bcrypt, 10 salt rounds — OWASP default) ──
  const passwordHash = await bcrypt.hash(payload.password, 10);

  // ── Generate OTP ──
  // In non-production: fixed "123456" so load-test tools (k6) can verify
  // In production: cryptographically secure 6-digit OTP
  const otp =
    process.env.NODE_ENV === "production" ? generateOTP() : "123456";

  // ── Stage everything in the LRU cache (key = email) ──
  registrationCache.set(normalizedEmail, {
    otp,
    attempts: 0,
    payload: {
      registerNumber: payload.register_number,
      fullName: payload.full_name,
      email: normalizedEmail,
      phone: payload.phone,
      college: payload.college,
      department: payload.department,
      year: payload.year,
      gender: payload.gender,
      passwordHash,
    },
  });

  // ── Enqueue OTP delivery via graphile-worker ──
  await addJob("send-otp", { email: normalizedEmail, otp });

  return { message: "OTP sent to your email" };
}

/**
 * Verify the OTP and promote the staged registration into PostgreSQL.
 *
 * Security measures:
 * - Double-submit mutex prevents concurrent verify race conditions.
 * - Timing-safe OTP comparison via crypto.timingSafeEqual.
 * - 3-strike lockout deletes the cache entry after 3 failures.
 * - Replay protection: cache entry is deleted immediately on success.
 *
 * On success:
 * - Inserts user into the `users` table (csea_code auto-generated by DB).
 * - Enqueues a `generate-ticket` job for the confirmation email + QR code.
 * - Returns the auto-generated csea_code.
 */
async function verifyRegistration(
  input: RegistrationVerifyInput,
): Promise<{ cseaCode: string }> {
  const normalizedEmail = input.email.trim().toLowerCase();
  const providedOtp = input.otp.trim();

  // ── Double-submit protection (synchronous Set check) ──
  if (verificationMutex.has(normalizedEmail)) {
    throwError("Verification already in progress", 409);
  }
  verificationMutex.add(normalizedEmail);

  try {
    // ── Fetch staged data from LRU cache ──
    const staged = registrationCache.get(normalizedEmail);

    if (!staged) {
      throwError(
        "Session expired or invalid. Please register again.",
        400,
      );
    }

    // ── Timing-safe OTP comparison ──
    const isValid = compareOTP(providedOtp, staged.otp);

    if (!isValid) {
      staged.attempts += 1;

      if (staged.attempts >= 3) {
        // 3-strike rule: nuke the cache entry
        registrationCache.delete(normalizedEmail);
        throwError(
          "Too many failed attempts. Please register again.",
          400,
        );
      }

      // Update the cache with incremented attempt counter
      registrationCache.set(normalizedEmail, staged);
      throwError(
        `Invalid OTP. ${3 - staged.attempts} attempt(s) remaining.`,
        400,
      );
    }

    // ── Replay protection: delete cache entry immediately ──
    registrationCache.delete(normalizedEmail);

    // ── Insert verified user into PostgreSQL ──
    const { payload } = staged;
    let newUser: { userId: number; cseaCode: string | null };

    try {
      const rows = await db
        .insert(users)
        .values({
          register_number: payload.registerNumber,
          full_name: payload.fullName,
          email: payload.email,
          phone: payload.phone,
          college: payload.college,
          department: payload.department,
          year: payload.year,
          gender: payload.gender,
          password_hash: payload.passwordHash,
          created_at: new Date(),
        })
        .returning({
          userId: users.user_id,
          cseaCode: users.csea_code,
        });

      newUser = rows[0];
    } catch (error) {
      handleDbError(error);
    }

    const cseaCode = newUser.cseaCode!;

    // ── Enqueue ticket generation (QR code + confirmation email) ──
    await addJob("generate-ticket", {
      email: payload.email,
      cseaCode,
      fullName: payload.fullName,
      registerNumber: payload.registerNumber,
      college: payload.college,
      department: payload.department,
    });

    return { cseaCode };
  } finally {
    // Always release the mutex
    verificationMutex.delete(normalizedEmail);
  }
}

export default { initiateRegistration, verifyRegistration };
